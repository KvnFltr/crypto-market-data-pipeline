def throughput(d: Data, mac: Macros) -> None:
    fig, ax = plt.subplots(figsize=(TEXT_WIDTH, 2.4))
    shade(ax, d.windows, legend=True)

    def full_minute(m: datetime) -> bool:  # entirely inside a run
        return any(r["start"] <= m and m + timedelta(minutes=1) <= r["end"] for r in d.runs.values())

    for v in VENUES:
        rows = [r for r in d.messages if r["venue"] == v and full_minute(ts(r["minute"]))]
        x = [ts(r["minute"]) for r in rows]
        y = [int(r["live_trades"]) / 60 for r in rows]
        ax.plot(*broken(x, y, 150), color=COLOR[v], label=NAMES[v], lw=1.0)
    ax.set_yscale("log")
    ax.set_ylim(bottom=0.5)
    ax.set_ylabel("live trades per second")
    time_axis(ax)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=5, fontsize=7)
    fig.tight_layout()
    save(fig, "throughput")

    per_minute: dict[str, int] = defaultdict(int)
    for r in d.messages:
        per_minute[r["minute"]] += int(r["live_trades"])
    busiest = max(per_minute.values(), default=0) / 60
    mac.add("BusiestTradesPerS", f"{busiest:.0f}")
    if d.bench:
        best = max(float(r["fresh_rows_per_s"]) for r in d.bench if r["method"] == "copy_dedup")
        mac.add("CapacityRatio", f"{best / busiest:.0f}" if busiest else "--")
    total = sum(int(r["trades"]) for r in d.counts)
    recovered = sum(int(r["recovered"]) for r in d.counts)
    mac.add("TotalTradesText", thousands(total))
    mac.add("TotalLive", thousands(total - recovered))
    mac.add("TotalRecoveredTrades", thousands(recovered))
    b, c = d.runs.get("baseline"), d.runs.get("chaos")
    if b and c:
        mac.add("BaselineMinutes", f"{(b['end'] - b['start']).total_seconds() / 60:.0f}")
        mac.add("ChaosMinutes", f"{(c['end'] - c['start']).total_seconds() / 60:.0f}")
        mac.add("StopMinutes", f"{(c['start'] - b['end']).total_seconds() / 60:.1f}")
        mac.add("TotalHours", f"{(c['end'] - b['start']).total_seconds() / 3600:.1f}")
        mac.add("ExperimentDate", b["start"].strftime("%d %B %Y"))
        mac.add("ExperimentStart", b["start"].strftime("%H:%M"))
        mac.add("ExperimentEnd", c["end"].strftime("%H:%M"))
    q = d.windows.get("baseline_quiet")
    if q:
        mac.add("QuietMinutes", f"{float(q['minutes']):.0f}")
    i = d.windows.get("noisy")
    if i:
        mac.add("NoisyMinutes", f"{float(i['minutes']):.0f}")

    lines = [
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Run & Venue & Trades stored & live & recovered \\",
        r"\midrule",
    ]
    for run in ("baseline", "chaos"):
        rows = [r for r in d.counts if r["run"] == run]
        first = True
        for v in VENUES:
            vr = [r for r in rows if r["venue"] == v]
            t, live, rec = (sum(int(r[k]) for r in vr) for k in ("trades", "live", "recovered"))
            lines.append(
                f"{run if first else ''} & {NAMES[v]} & {thousands(t)} & {thousands(live)} & {thousands(rec)} \\\\"
            )
            first = False
        if run == "baseline":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("table_runs.tex", lines)


def latency(d: Data, mac: Macros) -> None:
    window = "baseline_quiet"
    offset, unc, lo, hi = d.clock_offset_ms(window)
    mac.add("QuietOffsetMs", f"\\ensuremath{{{offset:+.0f}}}")
    mac.add("QuietOffsetRangeMs", f"\\ensuremath{{{lo:+.0f}}}" + " to " + f"\\ensuremath{{{hi:+.0f}}}")
    mac.add("QuietOffsetUncMs", f"{unc:.1f}")

    # CDF from the histogram (latencies already corrected minute by minute at export)
    fig, ax = plt.subplots(figsize=(TEXT_WIDTH * 0.62, 2.8))
    for v in VENUES:
        rows = sorted(
            (r for r in d.histogram if r["window"] == window and r["venue"] == v), key=lambda r: int(r["bin"])
        )
        n = np.array([int(r["n"]) for r in rows], dtype=float)
        upper = np.array([float(r["upper_ms"]) for r in rows])
        keep = np.isfinite(upper)
        cdf = np.cumsum(n) / n.sum()
        ax.step(upper[keep], cdf[keep], where="post", color=COLOR[v], label=NAMES[v])
        if v in FIBRE_BOUND_MS:
            ax.axvline(FIBRE_BOUND_MS[v], color=COLOR[v], ls=":", lw=0.9)
    ax.set_xscale("log")
    ax.set(
        xlabel="exchange time to receipt (ms, clock-corrected)", ylabel="fraction of trades", ylim=(0, 1.01)
    )
    ax.legend(loc="lower right")
    ax.text(
        0.97,
        0.45,
        "dotted: speed-of-light\nbound in fibre",
        transform=ax.transAxes,
        fontsize=7,
        color=MUTED,
        ha="right",
    )
    fig.tight_layout()
    save(fig, "latency_cdf")

    # per-minute p50 / p99 over the whole experiment
    fig, ax = plt.subplots(figsize=(TEXT_WIDTH, 2.6))
    shade(ax, d.windows, legend=True)
    for v in VENUES:
        rows = [r for r in d.minutes if r["venue"] == v and int(r["n"]) >= 20]
        x = [ts(r["minute"]) for r in rows]
        qs = [json.loads(r["q"]) for r in rows]
        ax.plot(*broken(x, [q[1] for q in qs], 150), color=COLOR[v], lw=1.1, label=f"{NAMES[v]} median")
        ax.plot(
            *broken(x, [q[3] for q in qs], 150),
            color=COLOR[v],
            lw=0.7,
            ls="--",
            alpha=0.8,
            label=f"{NAMES[v]} p99",
        )
    ax.set_yscale("log")
    ax.set_ylabel("latency per minute (ms, clock-corrected)")
    time_axis(ax)
    ax.legend(loc="upper center", ncol=4, fontsize=6.5, bbox_to_anchor=(0.5, 1.22))
    fig.tight_layout()
    save(fig, "latency_time")

    # table for the quiet baseline window, plus ping round trips
    lines = [
        r"\begin{tabular}{lrrrrrrrrr}",
        r"\toprule",
        r"Venue & Trades & min & p1 & p50 & p90 & p99 & p99.9 & max & ping RTT/2 \\",
        r"\midrule",
    ]
    for v in VENUES:
        row = next((r for r in d.summary if r["window"] == window and r["venue"] == v), None)
        if row is None:
            continue
        q = json.loads(row["q"])  # quantiles 0.001, 0.01, 0.1, 0.5, 0.9, 0.99, 0.999
        mn, mx = float(row["min_ms"]), float(row["max_ms"])
        rtt = d.prom_value(window, "ws_rtt", 0.5, v) * 1e3 / 2
        lines.append(
            f"{NAMES[v]} & {thousands(float(row['n']))} & {mn:.1f} & {q[1]:.1f} & {q[3]:.1f} & {q[4]:.1f} & "
            f"{q[5]:.0f} & {q[6]:.0f} & {mx:.0f} & {rtt:.1f} \\\\"
        )
        cap = v.capitalize()
        mac.add(f"Lat{cap}Pfifty", f"{q[3]:.0f}")
        mac.add(f"Lat{cap}Pninetynine", f"{q[5]:.0f}")
        mac.add(f"Lat{cap}Min", f"{mn:.1f}")
        mac.add(f"Rtt{cap}Half", f"{rtt:.0f}")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("table_latency.tex", lines)


def clock(d: Data, mac: Macros) -> None:
    fig, ax = plt.subplots(figsize=(TEXT_WIDTH, 2.5))
    shade(ax, d.windows)
    styles = {"time.cloudflare.com": "#1baf7a", "time.google.com": "#2a78d6"}
    for ref, color in styles.items():
        rows = [s for s in d.clock if s["reference"] == ref]
        x = [ts(s["ts"]) for s in rows]
        y = [float(s["offset_s"]) * 1e3 for s in rows]
        e = [float(s["delay_s"]) * 1e3 / 2 for s in rows]
        ax.errorbar(x, y, yerr=e, fmt="o", ms=2.5, lw=0.6, color=color, alpha=0.85, label=f"NTP {ref}")
    rows = [s for s in d.clock if s["reference"] == "binance-rest"]
    ax.plot(
        [ts(s["ts"]) for s in rows],
        [float(s["offset_s"]) * 1e3 for s in rows],
        "x",
        ms=3,
        color="#eb6834",
        alpha=0.7,
        label=r"Binance server time (uncertainty $\approx\pm$130 ms)",
    )
    minutes = [(ts(r["minute"]), float(r["offset_ms"])) for r in d.clock_minutes]
    ax.plot(
        *broken([m for m, _ in minutes], [o for _, o in minutes], 90),
        color=INK,
        lw=0.9,
        label="correction applied (best sample)",
    )
    all_ntp = [s for s in d.clock if s["reference"] != "binance-rest"]
    delays = sorted(float(s["delay_s"]) * 1e3 for s in all_ntp)
    center = st.median(o for _, o in minutes) if minutes else 0.0
    ax.set_ylim(center - 35, center + 35)  # samples outside carry error bars that contain the truth
    ax.set_ylabel("reference $-$ local clock (ms)")
    time_axis(ax)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=2, fontsize=7)
    fig.tight_layout()
    save(fig, "clock")

    offsets = [float(s["offset_s"]) * 1e3 for s in all_ntp]
    if len(minutes) > 10:
        t0 = minutes[0][0]
        hours = np.array([(m - t0).total_seconds() / 3600 for m, _ in minutes])
        slope = float(np.polyfit(hours, np.array([o for _, o in minutes]), 1)[0])
        mac.add("ClockDriftMsPerHour", f"{slope:.1f}")
        mac.add("ClockDriftPpm", f"{abs(slope) / 3600 * 1e3:.1f}")
    mac.add("NtpSamples", str(len(all_ntp)))
    mac.add("NtpDelayMedianMs", f"{st.median(delays):.1f}")
    best = [
        float(s["offset_s"]) * 1e3 for s in all_ntp if float(s["delay_s"]) * 1e3 <= delays[len(delays) // 4]
    ]
    mac.add("NtpBestOffsetMedianMs", f"\\ensuremath{{{st.median(best):+.1f}}}")
    mac.add("NtpBestOffsetMinMs", f"\\ensuremath{{{min(best):+.1f}}}")
    mac.add("NtpBestOffsetMaxMs", f"\\ensuremath{{{max(best):+.1f}}}")
    mac.add("NtpOffsetMinMs", f"\\ensuremath{{{min(offsets):+.0f}}}")
    mac.add("NtpOffsetMaxMs", f"\\ensuremath{{{max(offsets):+.0f}}}")
    mac.add("NtpDelayMaxMs", f"{max(delays):.0f}")
    bn = [s for s in d.clock if s["reference"] == "binance-rest"]
    if bn:
        bbest = min(bn, key=lambda s: float(s["delay_s"]))
        mac.add("BinanceRestOffsetMs", f"\\ensuremath{{{float(bbest['offset_s']) * 1e3:+.0f}}}")
        mac.add("BinanceRestUncMs", f"{float(bbest['delay_s']) * 1e3 / 2:.0f}")


def probe(d: Data, mac: Macros) -> None:
    # Both series are raw (same local clock); shift them by the clock offset of the minute so that the
    # plotted values are on the reference time scale. Their difference is unaffected.
    pipe = {
        int(ts(r["second"]).timestamp()): float(r["recv_minus_e_p50_ms"]) + float(r["clock_offset_ms"])
        for r in d.seconds
    }
    ctrl = {
        int(r["second"]): float(r["p50_ms"]) + d.offset_at(datetime.fromtimestamp(int(r["second"]), UTC))
        for r in d.probe
    }
    common = sorted(set(pipe) & set(ctrl))

    def in_window(s: int, name: str) -> bool:
        w = d.windows.get(name)
        segs = (w["segs"] or [(w["start"], w["end"])]) if w is not None else []
        return any(a.timestamp() <= s <= b.timestamp() for a, b in segs)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(TEXT_WIDTH, 2.8), gridspec_kw={"width_ratios": [1.5, 1]})
    shade(ax1, d.windows, legend=True)
    x = [datetime.fromtimestamp(s, UTC) for s in common]
    ax1.plot(
        *broken(x, [ctrl[s] for s in common], 30), color=COLOR["probe"], lw=0.6, label="independent probe"
    )
    ax1.plot(
        *broken(x, [pipe[s] for s in common], 30), color=COLOR["binance"], lw=0.6, alpha=0.8, label="pipeline"
    )
    ax1.set_yscale("log")
    ax1.set_ylabel("median $t_{rx} - E$ per second (ms)")
    time_axis(ax1)
    ax1.set_title("(a) Binance BTC-USDT, same machine", loc="left")
    ax1.legend(loc="upper right", fontsize=6.5)

    groups = {
        "quiet": [s for s in common if in_window(s, "baseline_quiet") or in_window(s, "chaos")],
        "noisy": [s for s in common if in_window(s, "noisy")],
    }
    for name, color in (("quiet", "#2a78d6"), ("noisy", "#e34948")):
        diff = np.array([pipe[s] - ctrl[s] for s in groups[name]])
        if len(diff):
            diff = np.sort(diff)
            ax2.plot(
                diff,
                1 - np.arange(len(diff)) / len(diff),
                color=color,
                label="host quiet" if name == "quiet" else "noisy neighbour",
            )
    ax2.set_xscale("symlog", linthresh=1)
    ax2.set_xlim(-3, 3000)
    ax2.set_yscale("log")
    ax2.set(xlabel="pipeline $-$ probe (ms)", ylabel="fraction of seconds above")
    ax2.set_title("(b) excess latency of the pipeline", loc="left")
    ax2.legend(loc="lower left", fontsize=6.5)
    fig.tight_layout(w_pad=1.5)
    save(fig, "probe")

    for name, secs in groups.items():
        if not secs:
            continue
        diff = sorted(pipe[s] - ctrl[s] for s in secs)
        tag = "Quiet" if name == "quiet" else "Noisy"
        mac.add(f"Probe{tag}Seconds", thousands(len(secs)))
        mac.add(f"Probe{tag}DiffMedianMs", f"{st.median(diff):.1f}")
        mac.add(f"Probe{tag}DiffPninetynineMs", f"{diff[int(0.99 * (len(diff) - 1))]:.0f}")
        mac.add(f"Probe{tag}PipeOverHalfSec", str(sum(pipe[s] > 500 for s in secs)))
        mac.add(f"Probe{tag}ProbeOverHalfSec", str(sum(ctrl[s] > 500 for s in secs)))
        mac.add(f"Probe{tag}Corr", f"{st.correlation([pipe[s] for s in secs], [ctrl[s] for s in secs]):.2f}")
    if common:
        mac.add("ProbeMedianMs", f"{st.median(ctrl[s] for s in common):.1f}")
        mac.add("PipelineMedianMs", f"{st.median(pipe[s] for s in common):.1f}")
        mac.add("ProbeMaxMs", f"{max(float(r['max_ms']) for r in d.probe):.0f}")
    e_minus_t = [float(r["e_minus_t_p50_ms"]) for r in d.seconds]
    if e_minus_t:
        mac.add("EminusTMedianMs", f"{st.median(e_minus_t):.2f}")
        mac.add("EminusTMaxMs", f"{max(float(r['e_minus_t_max_ms']) for r in d.seconds):.0f}")


def losses(d: Data, mac: Macros) -> None:
    runs = {r["run_id"]: label for label, r in d.runs.items()}
    # downtime of each disconnection: disconnected -> next connected, per venue
    downtimes: dict[tuple[str, str], list[tuple[datetime, float, str]]] = defaultdict(list)
    last_down: dict[str, tuple[datetime, str]] = {}
    for e in d.events:
        label = runs.get(e["run_id"], "")
        if e["event"] == "disconnected":
            # failed reconnection attempts do not end a session: keep the time the session ended
            if e["reason"] != "connect_error" and e["venue"] not in last_down:
                last_down[e["venue"]] = (ts(e["ts"]), e["reason"])
        elif e["venue"] in last_down:
            t, reason = last_down.pop(e["venue"])
            downtimes[(label, e["venue"])].append((t, (ts(e["ts"]) - t).total_seconds(), reason))

    trade_gaps = [g for g in d.gaps if g["stream"] == "trades"]
    book_gaps = [g for g in d.gaps if g["stream"] == "book"]

    # gap size against downtime during fault injection
    fig, ax = plt.subplots(figsize=(TEXT_WIDTH * 0.62, 2.7))
    for v in VENUES:
        pts = []
        for t_down, dt, _reason in downtimes.get(("chaos", v), []):
            sizes = [
                int(g["size"])
                for g in trade_gaps
                if g["venue"] == v
                and g["after_reconnect"] == "True"
                and 0 <= (ts(g["detected_at"]) - t_down).total_seconds() <= dt + 120
            ]
            if sizes:
                pts.append((dt, sum(sizes)))
        if pts:
            ax.scatter(
                [p[0] for p in pts],
                [p[1] for p in pts],
                color=COLOR[v],
                marker=MARKER[v],
                s=14,
                label=NAMES[v],
            )
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set(xlabel="time disconnected (s)", ylabel="trades missed (both symbols)")
    ax.text(
        0.97,
        0.06,
        "rightmost points: host suspended",
        transform=ax.transAxes,
        ha="right",
        fontsize=7,
        color=MUTED,
    )
    ax.legend(loc="upper left")
    fig.tight_layout()
    save(fig, "gaps_downtime")

    # table per run and venue
    lines = [
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r"Run & Venue & Disconn. & \multicolumn{3}{c}{Trade gaps} & Missed & Recovered & Book \\",
        r"\cmidrule(lr){4-6}",
        r" & & & in session & reconnect & restart & trades & trades & resyncs \\",
        r"\midrule",
    ]
    totals = {"missing": 0, "recovered": 0, "disconnects_chaos": 0}
    for run in ("baseline", "chaos"):
        rid = d.runs[run]["run_id"] if run in d.runs else None
        first = True
        for v in VENUES:
            g = [x for x in trade_gaps if x["run_id"] == rid and x["venue"] == v]
            bk = [x for x in book_gaps if x["run_id"] == rid and x["venue"] == v]
            disc = sum(  # sessions that ended, whatever the reason (failed attempts excluded)
                1
                for e in d.events
                if e["run_id"] == rid
                and e["venue"] == v
                and e["event"] == "disconnected"
                and e["reason"] != "connect_error"
            )
            # the first gap of each symbol in the chaos run spans the planned stop: a restart gap
            first_ids = {}
            for x in sorted(g, key=lambda x: int(x["gap_id"])):
                first_ids.setdefault(x["symbol"], x["gap_id"])
            # gaps carry an explicit cause when recorded by a recent version of the pipeline
            restart = [
                x
                for x in g
                if x.get("cause") == "restart"
                or (
                    not x.get("cause")
                    and run == "chaos"
                    and x["gap_id"] in first_ids.values()
                    and x["after_reconnect"] == "True"
                )
            ]
            reconnect = [x for x in g if x["after_reconnect"] == "True" and x not in restart]
            in_session = [x for x in g if x["after_reconnect"] == "False"]
            missing = sum(int(x["size"]) for x in g)
            recovered = sum(int(x["recovered"]) for x in g)
            totals["missing"] += missing
            totals["recovered"] += recovered
            if run == "chaos":
                totals["disconnects_chaos"] += sum(
                    1
                    for e in d.events
                    if e["run_id"] == rid
                    and e["venue"] == v
                    and e["event"] == "disconnected"
                    and e["reason"] == "chaos"
                )
            lines.append(
                f"{run if first else ''} & {NAMES[v]} & {disc} & {len(in_session)} & {len(reconnect)} & "
                f"{len(restart)} & {thousands(missing)} & {thousands(recovered)} & {len(bk)} \\\\"
            )
            first = False
        if run == "baseline":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("table_gaps.tex", lines)

    mac.add("TotalMissing", thousands(totals["missing"]))
    mac.add("TotalRecovered", thousands(totals["recovered"]))
    pct = 100 * totals["recovered"] / totals["missing"] if totals["missing"] else 100.0
    mac.add("RecoveredPctText", f"{pct:.2f}\\%" if pct < 100 else "100\\%")
    mac.add("ChaosDisconnects", str(totals["disconnects_chaos"]))
    mac.add("BookResyncs", str(len(book_gaps)))
    mac.add("InSessionGaps", str(sum(1 for g in trade_gaps if g["after_reconnect"] == "False")))
    unrec = sum(int(g["size"]) - int(g["recovered"]) for g in trade_gaps)
    mac.add("UnrecoveredTotal", thousands(unrec))
    base_disc = [
        e
        for e in d.events
        if d.runs.get("baseline")
        and e["run_id"] == d.runs["baseline"]["run_id"]
        and e["event"] == "disconnected"
    ]
    mac.add("BaselineDisconnects", str(len(base_disc)))
    mac.add(
        "BaselineDisconnectReasons",
        ", ".join(sorted({f"{NAMES.get(e['venue'], e['venue'])} ({e['reason']})" for e in base_disc}))
        or "none",
    )
    chaos_dt = [
        dt for (label, _v), lst in downtimes.items() if label == "chaos" for _t, dt, r in lst if r == "chaos"
    ]
    if chaos_dt:
        mac.add("ChaosDowntimeMedianS", f"{st.median(chaos_dt):.1f}")
        mac.add("ChaosDowntimeTotalS", f"{sum(chaos_dt):.0f}")
    resolve = [
        (ts(g["resolved_at"]) - ts(g["detected_at"])).total_seconds() for g in trade_gaps if g["resolved_at"]
    ]
    if resolve:
        mac.add("RepairMedianS", f"{st.median(resolve):.1f}")
        mac.add("RepairMaxS", f"{max(resolve):.0f}")
    sizes = [(int(g["size"]), g["venue"], g["symbol"]) for g in trade_gaps]
    if sizes:
        size, venue, symbol = max(sizes)
        mac.add("LargestGap", thousands(size))
        mac.add("LargestGapWhere", f"{NAMES[venue]} {symbol}")
    restart_missing = sum(int(g["size"]) for g in trade_gaps if g.get("cause") == "restart")
    mac.add("RestartMissing", thousands(restart_missing))
    chaos = d.windows.get("chaos")
    if chaos and len(chaos["segs"]) > 1:
        (_a, b), (c, _d) = chaos["segs"][0], chaos["segs"][1]
        mac.add("SuspensionMinutes", f"{(c - b).total_seconds() / 60:.0f}")
        mac.add("SuspensionStart", b.strftime("%H:%M"))
        resumed = [g for g in trade_gaps if b <= ts(g["detected_at"]) <= c + timedelta(minutes=2)]
        mac.add("SuspensionMissing", thousands(sum(int(g["size"]) for g in resumed)))
        mac.add("SuspensionRecovered", thousands(sum(int(g["recovered"]) for g in resumed)))
    failed = sum(1 for e in d.events if e["reason"] == "connect_error")
    mac.add("FailedAttempts", str(failed))
    crossed = sum(int(q["crossed"]) for q in d.quotes)
    mac.add("QuotesStored", thousands(sum(int(q["quotes"]) for q in d.quotes)))
    mac.add("CrossedQuotes", str(crossed))


def audit(d: Data, mac: Macros) -> None:
    if not d.audit:
        for k in ("AuditReference", "AuditMissing", "AuditMismatched", "AuditUnexpected", "AuditRecovered"):
            mac.add(k, "--")
        write_table(
            "table_audit.tex", [r"\emph{audit not run: 	exttt{python analysis/export.py --audit}}"]
        )
        return
    lines = [
        r"\begin{tabular}{lllrrrrrr}",
        r"\toprule",
        r"Run & Venue & Symbol & Reference & Stored & Recovered & Missing & Extra & Altered \\",
        r"\midrule",
    ]
    prev = None
    for a in d.audit:
        run = a["run"] if a["run"] != prev else ""
        if prev is not None and a["run"] != prev:
            lines.append(r"\midrule")
        prev = a["run"]
        lines.append(
            f"{run} & {NAMES[a['venue']]} & {a['symbol']} & {thousands(a['reference'])} & "
            f"{thousands(a['stored'])} & {thousands(a['stored_recovered'])} & {a['missing']} & "
            f"{a['unexpected']} & {a['mismatched']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("table_audit.tex", lines)
    mac.add("AuditReference", thousands(sum(a["reference"] for a in d.audit)))
    mac.add("AuditMissing", thousands(sum(a["missing"] for a in d.audit)))
    mac.add("AuditMismatched", thousands(sum(a["mismatched"] for a in d.audit)))
    mac.add("AuditUnexpected", thousands(sum(a["unexpected"] for a in d.audit)))
    mac.add("AuditRecovered", thousands(sum(a["stored_recovered"] for a in d.audit)))


def internals(d: Data, mac: Macros) -> None:
    rows = [
        ("ingest_trade", "Receipt to commit, trades", 1e3),
        ("ingest_quote", "Receipt to commit, quotes", 1e3),
        ("db_write_trades", "Batch write (COPY + insert)", 1e3),
        ("event_loop_lag", "Event loop lag", 1e3),
    ]
    windows = [w for w in ("baseline_quiet", "noisy", "chaos") if w in d.windows]
    header = " & ".join(f"\\multicolumn{{2}}{{c}}{{{WINDOW_TITLES[w]}}}" for w in windows)
    lines = [
        r"\begin{tabular}{l" + "rr" * len(windows) + "}",
        r"\toprule",
        f"Stage (ms) & {header} \\\\",
        "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(windows))),
        " & " + " & ".join(["p50 & p99"] * len(windows)) + r" \\",
        r"\midrule",
    ]
    for metric, title, scale in rows:
        cells = []
        for w in windows:
            cells += [fnum(d.prom_value(w, metric, 0.5) * scale), fnum(d.prom_value(w, metric, 0.99) * scale)]
        lines.append(f"{title} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("table_internal.tex", lines)
    for w, tag in (("baseline_quiet", "Quiet"), ("noisy", "Noisy"), ("chaos", "Chaos")):
        mac.add(f"Ingest{tag}Pfifty", fnum(d.prom_value(w, "ingest_trade", 0.5) * 1e3))
        mac.add(f"Ingest{tag}Pninetynine", fnum(d.prom_value(w, "ingest_trade", 0.99) * 1e3))
        mac.add(f"LoopLag{tag}Pninetynine", fnum(d.prom_value(w, "event_loop_lag", 0.99) * 1e3))
        mac.add(f"DbWrite{tag}Pninetynine", fnum(d.prom_value(w, "db_write_trades", 0.99) * 1e3))
    mac.add("ParseBinancePfiftyUs", fnum(d.prom_value("baseline_quiet", "parse", 0.5, "binance") * 1e6, 2))
    mac.add("BatchRowsQuietPfifty", fnum(d.prom_value("baseline_quiet", "batch_rows_trades", 0.5), 2))


def storage(d: Data, mac: Macros) -> None:
    if d.storage:
        t = next(r for r in d.storage if r["table"] == "trades")
        before, after = float(t["bytes_uncompressed"]), float(t["bytes_compressed"])
        mac.add("TradesRows", thousands(float(t["rows"])))
        mac.add("TradesMBUncompressed", f"{before / 2**20:.0f}")
        mac.add("TradesMBCompressed", f"{after / 2**20:.1f}")
        mac.add("CompressionRatio", f"{before / after:.1f}")
        mac.add("BytesPerTradeCompressed", f"{after / float(t['rows']):.0f}")
    if d.bench:
        lines = [
            r"\begin{tabular}{rrrrr}",
            r"\toprule",
            r"Batch & \multicolumn{2}{c}{COPY + deduplicating insert} & \multicolumn{2}{c}{executemany} \\",
            r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
            r"rows & new rows/s & replay rows/s & new rows/s & replay rows/s \\",
            r"\midrule",
        ]
        for batch in sorted({int(r["batch"]) for r in d.bench}):
            c = next(r for r in d.bench if int(r["batch"]) == batch and r["method"] == "copy_dedup")
            e = next(r for r in d.bench if int(r["batch"]) == batch and r["method"] == "executemany")
            lines.append(
                f"{thousands(batch)} & {thousands(float(c['fresh_rows_per_s']))} & "
                f"{thousands(float(c['replay_rows_per_s']))} & {thousands(float(e['fresh_rows_per_s']))} & "
                f"{thousands(float(e['replay_rows_per_s']))} \\\\"
            )
        lines += [r"\bottomrule", r"\end{tabular}"]
        write_table("table_storage.tex", lines)
        best = max(float(r["fresh_rows_per_s"]) for r in d.bench if r["method"] == "copy_dedup")
        mac.add("BenchBestRowsPerS", thousands(best))
        speedups = [
            float(c["fresh_rows_per_s"]) / float(e["fresh_rows_per_s"])
            for c in d.bench
            if c["method"] == "copy_dedup"
            for e in d.bench
            if e["method"] == "executemany" and e["batch"] == c["batch"]
        ]
        mac.add("BenchSpeedupMax", f"{max(speedups):.1f}")


def main() -> None:
    (REPORT / "figures").mkdir(parents=True, exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)
    setup_style()
    d = Data()
    mac = Macros()
    try:  # number of test cases as collected by pytest (parametrised cases included)
        out = subprocess.run(
            [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider"],
            capture_output=True,
            text=True,
            cwd=ROOT,
            timeout=120,
        )
        tests = next(
            line.split()[0]
            for line in out.stdout.splitlines()
            if " tests collected" in line or line.endswith(" tests")
        )
    except (OSError, subprocess.SubprocessError, StopIteration):
        tests = "--"
    mac.add("TestCount", tests)
    for step in (throughput, latency, clock, probe, losses, audit, internals, storage):
        step(d, mac)
    mac.write()
    print(f"figures in {REPORT / 'figures'}, tables and macros in {GEN}")


if __name__ == "__main__":
    main()
