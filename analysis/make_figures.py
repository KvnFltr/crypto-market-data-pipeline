# --------------------------------------------------------------------------- helpers
def read(name: str) -> list[dict[str, str]]:
    path = RES / name
    if not path.exists() or path.stat().st_size == 0:
        return []
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def ts(text: str) -> datetime:
    dt = datetime.fromisoformat(text)
    return dt if dt.tzinfo else dt.replace(tzinfo=UTC)


def fnum(x: float, digits: int = 3) -> str:
    if not math.isfinite(x):
        return "--"
    if x == 0:
        return "0"
    mag = math.floor(math.log10(abs(x)))
    d = max(0, digits - 1 - mag)
    return f"{x:,.{d}f}".replace(",", "\\,")


def thousands(n: float) -> str:
    return f"{round(n):,}".replace(",", "\\,")


class Macros:
    def __init__(self) -> None:
        self.lines = ["% Generated by analysis/make_figures.py -- do not edit by hand."]

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self) -> None:
        (GEN / "results.tex").write_text("\n".join(self.lines) + "\n", encoding="utf-8")


def write_table(name: str, lines: list[str]) -> None:
    (GEN / name).write_text(
        "% Generated by analysis/make_figures.py\n" + "\n".join(lines) + "\n", encoding="utf-8"
    )


def setup_style() -> None:
    logging.getLogger("fontTools").setLevel(logging.ERROR)
    family = "serif"
    kpse = shutil.which("kpsewhich")
    if kpse:
        try:
            out = subprocess.run([kpse, "lmroman10-regular.otf"], capture_output=True, text=True, timeout=30)
            path = out.stdout.strip()
            if path and Path(path).exists():
                font_manager.fontManager.addfont(path)
                family = font_manager.FontProperties(fname=path).get_name()
        except (OSError, subprocess.SubprocessError):
            pass
    plt.rcParams.update(
        {
            "font.family": family,
            "mathtext.fontset": "cm",
            "font.size": 9,
            "axes.titlesize": 9,
            "axes.labelsize": 9,
            "legend.fontsize": 7.5,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "axes.edgecolor": MUTED,
            "axes.labelcolor": INK,
            "xtick.color": MUTED,
            "ytick.color": MUTED,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.color": GRID,
            "grid.linewidth": 0.6,
            "axes.axisbelow": True,
            "lines.linewidth": 1.3,
            "lines.markersize": 4,
            "legend.frameon": False,
            "savefig.bbox": "tight",
            "savefig.pad_inches": 0.02,
            "pdf.fonttype": 42,
        }
    )


def save(fig: Any, name: str) -> None:
    fig.savefig(REPORT / "figures" / f"{name}.pdf", metadata={"CreationDate": None})
    (ROOT / "docs" / "img").mkdir(parents=True, exist_ok=True)
    fig.savefig(ROOT / "docs" / "img" / f"{name}.png", dpi=200)
    plt.close(fig)


def broken(x: list[datetime], y: list[float], max_gap_s: float = 90.0) -> tuple[list[Any], list[float]]:
    """Inserts a break (NaN) wherever consecutive points are further apart than `max_gap_s`."""
    xs: list[Any] = []
    ys: list[float] = []
    for i, (xi, yi) in enumerate(zip(x, y, strict=True)):
        if i and (xi - x[i - 1]).total_seconds() > max_gap_s:
            xs.append(x[i - 1] + (xi - x[i - 1]) / 2)
            ys.append(math.nan)
        xs.append(xi)
        ys.append(yi)
    return xs, ys


def time_axis(ax: Any) -> None:
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%H:%M", tz=UTC))
    ax.set_xlabel("time (UTC)")


def shade(ax: Any, windows: dict[str, dict[str, Any]], legend: bool = False) -> None:
    for name in ("noisy", "chaos"):
        w = windows.get(name)
        if w:
            ax.axvspan(
                w["start"],
                w["end"],
                color=SHADE[name],
                lw=0,
                zorder=0,
                label=("noisy neighbour" if name == "noisy" else "fault injection") if legend else None,
            )


# --------------------------------------------------------------------------- data
class Data:
    def __init__(self) -> None:
        self.runs = {
            r["label"]: {**r, "start": ts(r["started_at"]), "end": ts(r["ended_at"])}
            for r in read("runs.csv")
        }
        self.windows = {
            w["window"]: {
                **w,
                "start": ts(w["start"]),
                "end": ts(w["end"]),
                "segs": [
                    tuple(ts(x) for x in seg.split("/")) for seg in w.get("segments", "").split(";") if seg
                ],
            }
            for w in read("windows.csv")
        }
        self.clock = read("clock_samples.csv")
        self.clock_minutes = read("clock_minutes.csv")
        self._offset_by_minute = {ts(r["minute"]): float(r["offset_ms"]) for r in self.clock_minutes}
        self.events = read("connection_events.csv")
        self.gaps = read("gaps.csv")
        self.summary = read("latency_summary.csv")
        self.histogram = read("latency_histogram.csv")
        self.minutes = read("latency_minutes.csv")
        self.seconds = read("binance_seconds.csv")
        self.probe = read("probe_btcusdt.csv")
        self.messages = read("message_minutes.csv")
        self.counts = read("trade_counts.csv")
        self.quotes = read("quote_counts.csv")
        self.prom = read("prometheus_quantiles.csv")
        self.storage = read("storage.csv")
        self.bench = read("storage_benchmark.csv")
        audit = RES / "audit.json"
        self.audit: list[dict[str, Any]] = json.loads(audit.read_text()) if audit.exists() else []

    def clock_offset_ms(self, window: str) -> tuple[float, float, float, float]:
        """Median, min and max of the per-minute clock offset over a window, and the median uncertainty."""
        w = self.windows[window]
        rows = [r for r in self.clock_minutes if w["start"] <= ts(r["minute"]) <= w["end"]]
        if not rows:
            return 0.0, 0.0, 0.0, 0.0
        offsets = [float(r["offset_ms"]) for r in rows]
        unc = st.median(float(r["unc_ms"]) for r in rows)
        return st.median(offsets), unc, min(offsets), max(offsets)

    def offset_at(self, when: datetime) -> float:
        key = when.replace(second=0, microsecond=0)
        return self._offset_by_minute.get(key, 0.0)

    def prom_value(self, window: str, metric: str, q: float, label: str = "") -> float:
        for r in self.prom:
            if (
                r["window"] == window
                and r["metric"] == metric
                and float(r["quantile"]) == q
                and r["label"] == label
            ):
                return float(r["value"])
        return math.nan


